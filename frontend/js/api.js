// ── Status badge untuk bin ─────────────────────────────────────────
function statusBadge(status) {
  const map = { PENUH: ["badge-penuh", "badge"], SEDANG: ["badge-sedang", "badge"], NORMAL: ["badge-normal", "badge"] };
  const [cls] = map[status] || ["badge-normal", "badge"];
  return `<span class="tier-badge ${cls}" style="font-size:.72rem">${status}</span>`;
}

// ── Format number ──────────────────────────────────────────────────
function fmtNum(n) {
  if (!n && n !== 0) return "-";
  if (n >= 1000) return (n / 1000).toFixed(1) + "K";
  return n;
}

// ── Relative time ──────────────────────────────────────────────────
function relTime(dateStr) {
  if (!dateStr) return "-";
  const diff = Date.now() - new Date(dateStr);
  const m = Math.floor(diff / 60000);
  if (m < 1) return "baru saja";
  if (m < 60) return `${m} mnt lalu`;
  const h = Math.floor(m / 60);
  if (h < 24) return `${h} jam lalu`;
  return `${Math.floor(h / 24)} hari lalu`;
}

// ── Toast ──────────────────────────────────────────────────────────
function showToast(msg, type = "default", duration = 3200) {
  let c = document.getElementById("toast-container");
  if (!c) { c = document.createElement("div"); c.id = "toast-container"; document.body.appendChild(c); }
  const t = document.createElement("div");
  const icon = type === "success" ? "check-circle" : type === "error" ? "x-circle" : "zap";
  t.className = `et-toast ${type}`;
  t.innerHTML = `${lucideInline(icon, 15)} ${msg}`;
  c.appendChild(t);
  setTimeout(() => { t.style.opacity = "0"; t.style.transition = "opacity .3s"; setTimeout(() => t.remove(), 300); }, duration);
}

