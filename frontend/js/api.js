const API = "http://192.168.0.109:8000";

async function apiFetch(path, options = {}) {
  try {
    const res = await fetch(API + path, {
      headers: { "Content-Type": "application/json" },
      ...options,
    });
    if (!res.ok) {
      const err = await res.json().catch(() => ({ detail: "Error tidak diketahui" }));
      throw new Error(err.detail || "Request gagal");
    }
    return await res.json();
  } catch (e) { throw e; }
}

const apiGet = (path) => apiFetch(path);
const apiPost = (path, body) => apiFetch(path, { method: "POST", body: JSON.stringify(body) });

// ── Tier system (Copper → Adamantium) 9 tiers ────────────────────
const TIERS = [
  { name: "Copper",     minXp: 0,      cls: "tier-copper"     },
  { name: "Bronze",     minXp: 300,    cls: "tier-bronze"     },
  { name: "Silver",     minXp: 800,    cls: "tier-silver"     },
  { name: "Gold",       minXp: 2000,   cls: "tier-gold"       },
  { name: "Platinum",   minXp: 5000,   cls: "tier-platinum"   },
  { name: "Diamond",    minXp: 10000,  cls: "tier-diamond"    },
  { name: "Mithril",    minXp: 20000,  cls: "tier-mithril"    },
  { name: "Orichalcum", minXp: 35000,  cls: "tier-orichalcum" },
  { name: "Adamantium", minXp: 60000,  cls: "tier-adamantium" },
];

function getTier(xp) {
  for (let i = TIERS.length - 1; i >= 0; i--) {
    if (xp >= TIERS[i].minXp) return TIERS[i];
  }
  return TIERS[0];
}

function getNextTier(xp) {
  for (let i = 0; i < TIERS.length; i++) {
    if (xp < TIERS[i].minXp) return TIERS[i];
  }
  return null;
}

function getTierProgress(xp) {
  const current = getTier(xp);
  const next = getNextTier(xp);
  if (!next) return { pct: 100, xpLeft: 0, nextName: "MAX" };
  const pct = Math.round((xp - current.minXp) / (next.minXp - current.minXp) * 100);
  return { pct, xpLeft: next.minXp - xp, nextName: next.name };
}

// ── levelBadge ─────────────────────────────────────────────────────
function levelBadge(levelOrXp) {
  let tier;
  if (typeof levelOrXp === "number") {
    tier = getTier(levelOrXp);
  } else {
    tier = TIERS.find(t => t.name === levelOrXp) || TIERS[0];
  }
  return `<span class="tier-badge ${tier.cls}">${lucideInline("shield", 11)} ${tier.name}</span>`;
}

